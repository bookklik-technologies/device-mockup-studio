import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Keep original PNGs as the source of truth; no runtime image hosting is needed.
export async function embedDeviceArtwork() {
  const ids = (await readdir(new URL('../packages/presets/artwork/', import.meta.url))).filter(file => file.endsWith('.png')).sort().map(file => file.slice(0, -4));
  const entries = await Promise.all(ids.map(async id => {
    const png = await readFile(new URL(`../packages/presets/artwork/${id}.png`, import.meta.url));
    return `  ${JSON.stringify(id)}: ${JSON.stringify('data:image/png;base64,' + png.toString('base64'))}`;
  }));
  const target = new URL('../packages/presets/src/artwork-data.ts', import.meta.url);
  const source = '// Generated by scripts/embed-device-artwork.mjs. Do not edit.\nexport const artworkSources: Record<string, string> = {\n' + entries.join(',\n') + '\n};\n';
  if (await readFile(target, 'utf8').catch(() => '') !== source) await writeFile(target, source);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await embedDeviceArtwork();
